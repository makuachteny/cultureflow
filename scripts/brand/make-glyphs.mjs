#!/usr/bin/env node
/**
 * One-off: converts the brand wordmark + tagline into SVG outline paths
 * and writes them to scripts/brand/glyphs.json. The logo SVGs are used
 * as <img> sources, where web fonts never load, so text must be paths.
 *
 * Only re-run this when the name, tagline, or typeface changes:
 *
 *   curl -L -o /tmp/Archivo.ttf \
 *     "https://github.com/google/fonts/raw/main/ofl/archivo/Archivo%5Bwdth,wght%5D.ttf"
 *   npx -y -p fontkit@2 node scripts/brand/make-glyphs.mjs /tmp/Archivo.ttf
 *
 * Archivo is licensed under the SIL Open Font License 1.1 — outlines
 * derived from it may be embedded in the logo artwork.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const fontkit = require("fontkit");
const __dirname = dirname(fileURLToPath(import.meta.url));
const brand = JSON.parse(readFileSync(join(__dirname, "..", "..", "brand.config.json"), "utf8"));

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("usage: make-glyphs.mjs <path to Archivo[wdth,wght].ttf>");
  process.exit(1);
}
const base = fontkit.openSync(fontPath);

/** Lay out `text` at the given axes and return one combined path + bbox.
 *  With `splitAt`, also returns the glyphs before/after that index as
 *  separate paths (`a`, `b`) in the same coordinate space, so the two
 *  halves of the name can be coloured differently with kerning intact. */
function outline(text, { wght, wdth, tracking = 0, splitAt }) {
  const font = base.getVariation({ wght, wdth });
  const run = font.layout(text);
  let x = 0;
  const parts = [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  run.glyphs.forEach((g, i) => {
    const p = g.path.scale(1, -1).translate(x, 0); // font units are y-up
    parts.push(p.toSVG());
    const b = p.bbox;
    if (Number.isFinite(b.minX)) {
      minX = Math.min(minX, b.minX); maxX = Math.max(maxX, b.maxX);
      minY = Math.min(minY, b.minY); maxY = Math.max(maxY, b.maxY);
    }
    x += run.positions[i].xAdvance + tracking * font.unitsPerEm;
  });
  const r = (n) => Math.round(n * 10) / 10;
  const box = { x: r(minX), y: r(minY), w: r(maxX - minX), h: r(maxY - minY) };
  if (splitAt === undefined) return { d: parts.join(" "), ...box };
  return { a: parts.slice(0, splitAt).join(" "), b: parts.slice(splitAt).join(" "), ...box };
}

const glyphs = {
  _note: "Generated by scripts/brand/make-glyphs.mjs from Archivo (OFL). Do not edit by hand.",
  // Two-line wordmark: CULTURE / FLOW in wide black caps. FLOW is
  // coloured like the horns. Same axes so both lines share cap height.
  line1: outline(brand.nameFirst.toUpperCase(), { wght: 900, wdth: 112, tracking: 0.02 }),
  line2: outline(brand.nameSecond.toUpperCase(), { wght: 900, wdth: 112, tracking: 0.02 }),
  // One-line fallback for very wide, very short spaces.
  oneLine: outline(brand.name.toUpperCase(), { wght: 900, wdth: 112, tracking: 0.02, splitAt: brand.nameFirst.length }),
  tagline: outline(brand.shortTag, { wght: 600, wdth: 100 })
};
writeFileSync(join(__dirname, "glyphs.json"), JSON.stringify(glyphs, null, 2) + "\n");
console.log("wrote scripts/brand/glyphs.json", {
  line1: [glyphs.line1.w, glyphs.line1.h],
  line2: [glyphs.line2.w, glyphs.line2.h],
  tagline: [glyphs.tagline.w, glyphs.tagline.h]
});
