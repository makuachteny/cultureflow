/** width / height of each lockup's viewBox. Keep in sync with the
 *  "brand aspects" line printed by `npm run brand:build`. */
export const BRAND_ASPECTS = {
  horizontal: 657 / 202,
  stacked:    516 / 380,
  mark:       188 / 202
} as const;

export type BrandLogoVariant = keyof typeof BRAND_LOGOS;

/* ─── Derived helpers ─── */

/** "© 2026 CultureFlow. Built for every culture, wherever it gathers." */
export function copyrightLine(year: number = new Date().getFullYear()): string {
  return `© ${year} ${BRAND_NAME}. Built for every culture, wherever it gathers.`;
}

/** ARIA label for the brand-home link used in Header / Footer / auth pages. */
export const BRAND_HOME_LABEL = `${BRAND_NAME} — home`;
